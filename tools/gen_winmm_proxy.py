#!/usr/bin/env python3
"""Generate winmm.def, proxy_stubs.cpp and proxy_count.h from the real
SysWOW64\\winmm.dll's export table (SysWOW64, not System32: the game is
32-bit). Run from repo root: python tools/gen_winmm_proxy.py -- outputs are
committed, not regenerated by the build.
"""
import os
import pefile
import sys
from pathlib import Path

# SystemRoot (WINDIR as a fallback) names the Windows folder; SysWOW64 holds the 32-bit copy the game loads.
REAL_WINMM = os.path.join(os.environ.get("SystemRoot") or os.environ.get("WINDIR") or "", "SysWOW64", "winmm.dll")
OUT_DIR = Path(__file__).resolve().parent.parent / "src" / "nukepanel"

# Exports a real function of ours serves instead of the jump stub; its stub
# stays generated (unexported) and proxy_count.h names the export's index so
# the function can call the real one through g_np_real.
# timeGetTime: Game speed's scaled clock (gamespeed.cpp, docs/re/game-speed.md).
OVERRIDES = {"timeGetTime": "np_time_get_time"}


def main():
    pe = pefile.PE(REAL_WINMM, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
    exports = pe.DIRECTORY_ENTRY_EXPORT.symbols
    if not exports:
        sys.exit(f"no exports found in {REAL_WINMM}")

    # Stable order: by ordinal, so regenerating without an underlying DLL
    # change reproduces byte-identical output.
    exports = sorted(exports, key=lambda e: e.ordinal)

    entries = []
    for e in exports:
        name = e.name.decode('ascii') if e.name else None
        entries.append((name, e.ordinal))

    write_def(entries)
    write_stubs(entries)
    write_count_header(entries)
    print(f"generated winmm.def, proxy_stubs.cpp and proxy_count.h for {len(entries)} exports")


def write_def(entries):
    lines = ["; Generated by tools/gen_winmm_proxy.py from the real winmm.dll's",
             "; export table. Do not hand-edit -- regenerate instead.",
             ";",
             "; LIBRARY is deliberately omitted -- naming it here would stamp the",
             "; DLL's internal name, and the file must present itself as winmm.dll",
             "; by filename.",
             "EXPORTS"]
    for i, (name, ordinal) in enumerate(entries):
        if name is not None:
            lines.append(f"    {name}={OVERRIDES.get(name, f'np_stub_{i}')} @{ordinal}")
        else:
            lines.append(f"    np_stub_{i} @{ordinal} NONAME")
    path = OUT_DIR / "winmm.def"
    with open(path, "w", newline='\n') as f:
        f.write("\n".join(lines) + "\n")


def write_count_header(entries):
    lines = [
        "// Generated by tools/gen_winmm_proxy.py. Do not hand-edit.",
        "#pragma once",
        f"#define NP_EXPORT_COUNT {len(entries)}",
    ]
    for i, (name, _) in enumerate(entries):
        if name in OVERRIDES:
            lines.append(f"#define NP_INDEX_{name} {i}")
    path = OUT_DIR / "proxy_count.h"
    with open(path, "w", newline='\n') as f:
        f.write("\n".join(lines) + "\n")


def write_stubs(entries):
    n = len(entries)
    out = []
    out.append("// Generated by tools/gen_winmm_proxy.py from the real winmm.dll's export")
    out.append("// table. Do not hand-edit -- regenerate instead.")
    out.append("//")
    out.append("// np_stub_<i> is the exported entry point; it jumps through g_np_real[i],")
    out.append("// which starts at np_first_call_<i> and is filled in by np_resolve_all")
    out.append("// (proxy.cpp) on the first call into ANY export.")
    out.append("#include <windows.h>")
    out.append("#include \"proxy_count.h\"")
    out.append("")
    out.append("extern \"C\" void np_resolve_all(int);")
    out.append("extern \"C\" void np_report_missing(int);")
    out.append("")
    out.append(f"extern \"C\" void* g_np_real[NP_EXPORT_COUNT];")
    out.append(f"extern \"C\" void* g_np_missing[NP_EXPORT_COUNT];")
    out.append(f"extern \"C\" const char* const g_np_names[NP_EXPORT_COUNT];")
    out.append(f"extern \"C\" const unsigned short g_np_ords[NP_EXPORT_COUNT];")
    out.append("")

    # cdecl leaves its pushed arg on the stack after `call`; popad needs esp
    # back where pushad left it, so the arg is dropped before popad runs.
    for i in range(n):
        out.append(f"extern \"C\" __declspec(naked) void np_first_call_{i}(void) {{")
        out.append("  __asm {")
        out.append("    pushad")
        out.append(f"    push {i}")
        out.append("    call np_resolve_all")
        out.append("    add esp, 4")
        out.append("    popad")
        out.append(f"    jmp dword ptr [g_np_real + {i}*4]")
        out.append("  }")
        out.append("}")
    out.append("")

    for i in range(n):
        out.append(f"extern \"C\" __declspec(naked) void np_stub_{i}(void) {{")
        out.append("  __asm jmp dword ptr [g_np_real + " + str(i) + "*4]")
        out.append("}")
    out.append("")

    # np_report_missing (proxy.cpp) never returns (FatalAppExitA), so these
    # need no stack cleanup of their own -- there is no caller to return to.
    for i in range(n):
        out.append(f"extern \"C\" __declspec(naked) void np_missing_{i}(void) {{")
        out.append("  __asm {")
        out.append(f"    push {i}")
        out.append("    call np_report_missing")
        out.append("  }")
        out.append("}")
    out.append("")

    out.append(f"void* g_np_real[NP_EXPORT_COUNT] = {{")
    out.append(", ".join(f"(void*)np_first_call_{i}" for i in range(n)) + ",")
    out.append("};")
    out.append("")

    out.append(f"void* g_np_missing[NP_EXPORT_COUNT] = {{")
    out.append(", ".join(f"(void*)np_missing_{i}" for i in range(n)) + ",")
    out.append("};")
    out.append("")

    out.append(f"const char* const g_np_names[NP_EXPORT_COUNT] = {{")
    name_list = []
    for name, _ in entries:
        name_list.append(f"\"{name}\"" if name is not None else "nullptr")
    out.append(", ".join(name_list) + ",")
    out.append("};")
    out.append("")

    out.append(f"const unsigned short g_np_ords[NP_EXPORT_COUNT] = {{")
    out.append(", ".join(str(ordinal) for _, ordinal in entries) + ",")
    out.append("};")
    out.append("")

    path = OUT_DIR / "proxy_stubs.cpp"
    with open(path, "w", newline='\n') as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
